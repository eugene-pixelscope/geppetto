import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../web/workshop.js',import.meta.url),'utf8');
const {describeProgress,workshopScene,whaleIcon}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const now=1000000;
const run={id:'training',state:'running',phase:'RUNNING',last_success_at:now/1000,progress:{epoch:19,total:245,epoch_basis:'completed'}};
assert.equal(describeProgress(run,null,now).moving,true);
for(const state of ['succeeded','failed','stopped','queued'])assert.equal(describeProgress({...run,state},null,now).moving,false);
assert.equal(describeProgress({...run,fetch_error:'offline'},null,now).moving,false);
assert.equal(describeProgress(run,null,now+180001).moving,false);
assert.equal(describeProgress({...run,phase:'validation'},null,now).moving,false);
assert.equal(describeProgress(null,null,now).moving,false);
const html=workshopScene(run);
assert.ok(html.includes('19'));
assert.ok(html.includes('245'));
assert.ok(!html.includes('whale-art'));
assert.ok((html.includes('Start')&&html.includes('Finish'))||(html.includes('출발선')&&html.includes('도착지')));
assert.ok(html.includes(`aria-valuenow="${19/245*100}"`));
assert.ok(workshopScene({...run,state:'succeeded'}).includes('aria-valuenow="100"'));
assert.ok(!workshopScene(null).includes('aria-valuenow='));
assert.ok(!workshopScene({...run,progress:{epoch:10,total:0}}).includes('aria-valuenow='));
assert.ok(!whaleIcon.includes('WHALE'));
console.log('PASS: running-state animation, stale/error/terminal states, epoch route, arrival, unknown progress, logo');
